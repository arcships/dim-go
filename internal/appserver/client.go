package appserver

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"strconv"
	"sync"
	"sync/atomic"
	"time"
)

// defaultRequestTimeout bounds a Call whose context carries no deadline.
const defaultRequestTimeout = 30 * time.Second

// writeDeadliner is implemented by transports that can bound a single Write,
// such as net.Conn. When present, the request deadline also bounds the write so
// a peer that stops reading cannot hold a request past its timeout.
type writeDeadliner interface {
	SetWriteDeadline(t time.Time) error
}

// Notification is an incoming JSON-RPC notification. Params is retained
// verbatim so callers can decode methods unknown to this package.
type Notification struct {
	Method string
	Params json.RawMessage
}

// LocalError describes an error generated by the client rather than by the
// daemon. The AppError values are the protocol-contract names.
type LocalError struct {
	AppError string
	Err      error
}

func (e *LocalError) Error() string {
	if e.Err == nil {
		return "appserver: " + e.AppError
	}
	return "appserver: " + e.AppError + ": " + e.Err.Error()
}
func (e *LocalError) Unwrap() error { return e.Err }

// Client is a small JSON-RPC request correlator. It does not own discovery or
// socket lifecycle; rw is the already-established transport.
//
// Requests are written by a single writeLoop, which keeps frames ordered and
// whole. A caller abandons its write when its context is done: the write may
// still reach the peer later, but the pending entry is gone and any late reply
// is discarded. A transport that also implements writeDeadliner bounds the
// write so a peer that stops reading cannot pin the writer forever.
//
// Notifications is a lossless handoff: the reader blocks while the channel is
// full, so callers must keep draining Notifications for responses to keep
// flowing.
type Client struct {
	rw          io.ReadWriter
	fr          *FrameReader
	writes      chan writeRequest
	mu          sync.Mutex
	nextID      int64
	pending     map[string]chan rpcResponse
	notify      chan Notification
	errs        chan error
	dropped     atomic.Uint64
	streamTaken atomic.Bool
	done        chan struct{}
	closeOnce   sync.Once
}

// writeRequest is one framed request queued for the writer loop.
type writeRequest struct {
	data     []byte
	deadline time.Time
	done     chan error
}

type RPCError struct {
	Code    int             `json:"code"`
	Message string          `json:"message"`
	Data    json.RawMessage `json:"data,omitempty"`
}

func (e *RPCError) Error() string { return e.Message }

type rpcResponse struct {
	result json.RawMessage
	err    error
}

// NewClient starts the reader and writer loops over rw. Notifications and
// protocol/transport errors are available through Notifications and Errors.
// Malformed frames are reported on Errors without closing the connection; a
// transport failure ends both loops.
func NewClient(rw io.ReadWriter) *Client {
	c := &Client{rw: rw, fr: NewFrameReader(rw), writes: make(chan writeRequest), nextID: 1, pending: make(map[string]chan rpcResponse), notify: make(chan Notification, 32), errs: make(chan error, 8), done: make(chan struct{})}
	go c.readLoop()
	go c.writeLoop()
	return c
}
func (c *Client) Notifications() <-chan Notification { return c.notify }

// Done is closed once the client has shut down, either because Close was called
// or because the transport ended. It is the wire-layer signal contract §14
// turns into a domain resync when a session stream loses its transport.
func (c *Client) Done() <-chan struct{} { return c.done }

// Errors delivers protocol and transport reports. Delivery into the channel is
// best-effort while the buffer is full: every report that could not be
// buffered increments DroppedErrors instead of vanishing silently.
func (c *Client) Errors() <-chan error { return c.errs }

// DroppedErrors returns the cumulative number of error reports that Errors
// could not buffer. Callers that need a complete audit trail should drain
// Errors promptly and treat this counter as loss.
func (c *Client) DroppedErrors() uint64 { return c.dropped.Load() }

// takeStream claims the client's single session-stream slot. A Client owns one
// Notifications/Errors handoff, so at most one SessionStream may take it.
func (c *Client) takeStream() bool { return c.streamTaken.CompareAndSwap(false, true) }

// Call sends one request and waits for its response. A nil params value omits
// the params member. Without a context deadline the request times out after
// 30 seconds. The request is complete once Call returns: if the context is done
// while the transport write is still blocked, the caller stops waiting and the
// pending entry is dropped (a later reply is ignored).
func (c *Client) Call(ctx context.Context, method string, params any) (json.RawMessage, error) {
	if method == "" {
		return nil, errors.New("appserver: method must not be empty")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if _, ok := ctx.Deadline(); !ok {
		var cancel context.CancelFunc
		ctx, cancel = context.WithTimeout(ctx, defaultRequestTimeout)
		defer cancel()
	}
	if err := ctx.Err(); err != nil {
		return nil, localContextError(ctx)
	}
	id := c.allocateID()
	key := strconv.FormatInt(id, 10)
	ch := make(chan rpcResponse, 1)
	c.mu.Lock()
	select {
	case <-c.done:
		c.mu.Unlock()
		return nil, &LocalError{AppError: "connection_closed"}
	default:
	}
	c.pending[key] = ch
	c.mu.Unlock()
	msg := struct {
		JSONRPC string `json:"jsonrpc"`
		ID      int64  `json:"id"`
		Method  string `json:"method"`
		Params  any    `json:"params,omitempty"`
	}{"2.0", id, method, params}
	payload, err := json.Marshal(msg)
	if err != nil {
		c.removePending(key)
		return nil, err
	}
	payload = append(payload, '\n')
	deadline, _ := ctx.Deadline()
	req := writeRequest{data: payload, deadline: deadline, done: make(chan error, 1)}
	select {
	case c.writes <- req:
	case <-ctx.Done():
		c.removePending(key)
		return nil, localContextError(ctx)
	case <-c.done:
		c.removePending(key)
		return nil, &LocalError{AppError: "connection_closed"}
	}
	select {
	case err := <-req.done:
		if err != nil {
			c.removePending(key)
			return nil, writeError(ctx, err)
		}
	case <-ctx.Done():
		c.removePending(key)
		return nil, localContextError(ctx)
	case <-c.done:
		c.removePending(key)
		// A write failure can close the connection at the same moment; prefer
		// its more specific local error when it is already recorded.
		select {
		case err := <-req.done:
			if err != nil {
				return nil, writeError(ctx, err)
			}
		default:
		}
		return nil, &LocalError{AppError: "connection_closed"}
	}
	select {
	case r := <-ch:
		if r.err != nil {
			return nil, r.err
		}
		return r.result, nil
	case <-ctx.Done():
		c.removePending(key)
		return nil, localContextError(ctx)
	case <-c.done:
		c.removePending(key)
		return nil, &LocalError{AppError: "connection_closed"}
	}
}

// localContextError maps a finished context onto the protocol-contract local
// error names. -32000 is shared with daemon errors, so only AppError separates
// them.
func localContextError(ctx context.Context) error {
	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		return &LocalError{AppError: "request_timeout", Err: ctx.Err()}
	}
	return &LocalError{AppError: "request_aborted", Err: ctx.Err()}
}

func (c *Client) allocateID() int64 {
	c.mu.Lock()
	id := c.nextID
	c.nextID++
	c.mu.Unlock()
	return id
}
func (c *Client) removePending(key string) { c.mu.Lock(); delete(c.pending, key); c.mu.Unlock() }

// writeLoop performs queued writes one at a time, so frames stay ordered and
// whole, and exits when the client is closed.
func (c *Client) writeLoop() {
	for {
		select {
		case <-c.done:
			return
		default:
		}
		select {
		case <-c.done:
			return
		case req := <-c.writes:
			c.writeFrame(req)
		}
	}
}

// writeFrame writes one framed request and reports the outcome to the caller. A
// failed write may have emitted a partial frame, so the transport is shut down
// instead of leaving the stream desynced for the next request.
func (c *Client) writeFrame(req writeRequest) {
	if d, ok := c.rw.(writeDeadliner); ok && !req.deadline.IsZero() {
		if d.SetWriteDeadline(req.deadline) == nil {
			defer func() { _ = d.SetWriteDeadline(time.Time{}) }()
		}
	}
	_, err := c.rw.Write(req.data)
	req.done <- err
	if err != nil {
		c.report(fmt.Errorf("appserver: transport write: %w", err))
		c.shutdown()
	}
}

// writeError maps a failed write onto a local error. The context outcome wins
// when it is already known; otherwise a write deadline is a request timeout and
// anything else means the connection is no longer usable.
func writeError(ctx context.Context, err error) error {
	if ctx.Err() != nil {
		return localContextError(ctx)
	}
	if errors.Is(err, os.ErrDeadlineExceeded) {
		return &LocalError{AppError: "request_timeout", Err: err}
	}
	return &LocalError{AppError: "connection_closed", Err: err}
}

func (c *Client) readLoop() {
	defer c.shutdown()
	for {
		raw, err := c.fr.ReadFrame()
		if err != nil {
			if !errors.Is(err, io.EOF) {
				c.report(err)
			}
			return
		}
		// Frames are independent: a malformed frame is reported and the
		// connection stays usable (protocol-contract §19).
		if err := c.dispatch(raw); err != nil {
			c.report(err)
		}
	}
}

// dispatch delivers one frame to the notification channel or the matching
// pending request.
func (c *Client) dispatch(raw []byte) error {
	if err := ValidateEnvelope(raw); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(raw, &fields); err != nil {
		return err
	}
	if methodRaw, ok := fields["method"]; ok {
		// The client never serves peer requests, so a method with an id is a
		// protocol violation rather than a notification.
		if _, hasID := fields["id"]; hasID {
			return errors.New("appserver: notification must not carry an id")
		}
		var method string
		if err := json.Unmarshal(methodRaw, &method); err != nil {
			return err
		}
		var p json.RawMessage
		if x, ok := fields["params"]; ok {
			p = append(json.RawMessage(nil), x...)
		}
		select {
		case c.notify <- Notification{Method: method, Params: p}:
		case <-c.done:
		}
		return nil
	}
	idRaw := fields["id"]
	if e, ok := fields["error"]; ok && isJSONNull(idRaw) {
		// A null-id error belongs to no request: report it with its code and
		// message, never crash and never close the connection.
		var re RPCError
		if err := json.Unmarshal(e, &re); err != nil {
			return err
		}
		return fmt.Errorf("appserver: uncorrelated error reply: %w", &re)
	}
	key, err := responseKey(idRaw)
	if err != nil {
		return err
	}
	var r rpcResponse
	if e, ok := fields["error"]; ok {
		var re RPCError
		if err := json.Unmarshal(e, &re); err != nil {
			return err
		}
		r.err = &re
	} else {
		r.result = append(json.RawMessage(nil), fields["result"]...)
	}
	c.mu.Lock()
	ch, ok := c.pending[key]
	if ok {
		delete(c.pending, key)
	}
	c.mu.Unlock()
	if ok {
		ch <- r
	}
	// Replies for unknown ids are late successes for requests that already
	// timed out or were aborted; they are not protocol errors.
	return nil
}

func responseKey(raw json.RawMessage) (string, error) {
	raw = bytes.TrimSpace(raw)
	if len(raw) == 0 || isJSONNull(raw) {
		return "", errors.New("appserver: reply has invalid id")
	}
	var s string
	if json.Unmarshal(raw, &s) == nil {
		if n, err := strconv.ParseInt(s, 10, 64); err == nil && strconv.FormatInt(n, 10) == s {
			return strconv.FormatInt(n, 10), nil
		}
		return "s:" + s, nil
	}
	var n json.Number
	if json.Unmarshal(raw, &n) == nil {
		return n.String(), nil
	}
	return "", errors.New("appserver: reply id must be number or string")
}

func (c *Client) report(err error) {
	if err == nil {
		return
	}
	select {
	case c.errs <- err:
	default:
		c.dropped.Add(1)
	}
}
func (c *Client) shutdown() {
	c.closeOnce.Do(func() {
		close(c.done)
		c.mu.Lock()
		for key, ch := range c.pending {
			ch <- rpcResponse{err: &LocalError{AppError: "connection_closed"}}
			delete(c.pending, key)
		}
		c.mu.Unlock()
		if x, ok := c.rw.(io.Closer); ok {
			_ = x.Close()
		}
	})
}

// Close stops the client and closes rw when it implements io.Closer.
func (c *Client) Close() { c.shutdown() }
