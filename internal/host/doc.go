// 退出顺序与超时、诊断记录与进程级状态。
//
// 边界：
//   - 单实例用本地端点互斥。第一次启动监听端点；之后的启动把参数转交给已有实例后退出。
//     进程被强杀后残留的端点按"无人监听"清理后可重新占用，不依赖任何锁文件或状态文件。
//   - 启动按六阶段推进：单实例 → 装载本地状态 → 连服务 → 订阅 → 首轮历史 → 允许写。
//     每阶段完成或失败都写一条诊断；失败停在当前阶段，不推进后续阶段，也不提前允许写。
//     连上之前不允许发服务端请求，未连接不被当成空数据。
//   - 退出按五阶段推进：停止新意图 → 结束交互 → 关连接 → 回收自启服务 → 冲刷诊断。
//     每段各有超时，任一段超时或失败都记录后继续，不无限等待。
//   - 诊断只接受白名单字段：字段只能用本包的构造函数生成，字符串取值只有枚举与版本号，
//     没有自由文本入口，因此凭据与会话正文没有进入日志的通道。
//
// 不包含：界面、连接实现、各领域内部逻辑、应用更新的下载与切换。
